function buildHistory(
  baseKva: number,
  ratedKva: number,
  baseTemp: number,
  baseUnbalance: number,
  basePf: number,
  trendSlope = 0
): TelemetrySample[] {
  const samples: TelemetrySample[] = [];
  const now = new Date();
  for (let i = 23; i >= 0; i--) {
    const t = new Date(now.getTime() - i * 30000);
    const label = t.toTimeString().slice(0, 8);
    const wave = Math.sin((23 - i) * 0.45) * 0.045;
    const progress = (23 - i) / 23;
    const kva = Math.max(0, Number((baseKva * (1 + wave + trendSlope * progress)).toFixed(1)));
    const loadPct = Number(((kva / ratedKva) * 100).toFixed(1));
    const tempC = Number((baseTemp + wave * 8 + trendSlope * 14 * progress).toFixed(1));
    const unbalancePct = Number(Math.max(0, baseUnbalance + wave * 12).toFixed(1));
    samples.push({
      timestamp: label,
      loadKva: kva,
      loadPct,
      tempC,
      unbalancePct,
      pf: Number(Math.min(0.999, Math.max(0.78, basePf - wave * 0.04)).toFixed(3)),
    });
  }
  return samples;
}

